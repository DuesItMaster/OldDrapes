<script>
	
document.addEventListener('DOMContentLoaded', function () {
	var items = document.querySelectorAll('#idTab_0 .ajax_block_product');
	var previewImg = document.getElementById('item_selected_img');
	var previewLabel = document.getElementById('item_selected_label');

	items.forEach(function (item) {
		item.addEventListener('mouseenter', function () {
			var bgImg = item.style.backgroundImage;
			var match = bgImg.match(/url\(["']?([^"')]+)["']?\)/);
			if (match) {
				previewImg.classList.remove('visible');
				previewImg.src = match[1];
				previewImg.onload = function () {
					previewImg.classList.add('visible');
				};
			}
			var nameEl = item.querySelector('.price');
			if (nameEl) {
				previewLabel.textContent = nameEl.textContent;
			}
		});
	});
});
</script>